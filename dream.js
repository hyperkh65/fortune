/* ──────────────────────────────────────────────────────
   SEARCH INPUT
────────────────────────────────────────────────────── */
function updateClearBtn() {
  const btn = document.getElementById('searchClearBtn');
  if (!btn) return;
  btn.classList.toggle('visible', currentQuery.length > 0);
}

function initSearch() {
  const inp      = document.getElementById('dreamSearchInp');
  const clearBtn = document.getElementById('searchClearBtn');
  if (!inp) return;

  let debounceTimer;

  inp.addEventListener('input', () => {
    clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      currentQuery = inp.value.trim();
      expandedCards.clear();
      updateClearBtn();
      renderCards(searchDreams(currentQuery, currentCategory));
    }, 200);
  });

  inp.addEventListener('keydown', e => {
    if (e.key === 'Escape') {
      clearSearch();
    }
  });

  if (clearBtn) {
    clearBtn.addEventListener('click', clearSearch);
  }
}

function clearSearch() {
  const inp = document.getElementById('dreamSearchInp');
  if (inp) inp.value = '';
  currentQuery = '';
  expandedCards.clear();
  updateClearBtn();
  renderCards(searchDreams('', currentCategory));
}

/* ──────────────────────────────────────────────────────
   STARS CANVAS (subtle twinkle in dark bg)
────────────────────────────────────────────────────── */
function initDreamStars() {
  const canvas = document.getElementById('starsBg');
  if (!canvas) return;
  const ctx = canvas.getContext('2d');

  function resize() {
    canvas.width  = window.innerWidth;
    canvas.height = window.innerHeight;
  }
  resize();
  window.addEventListener('resize', resize);

  const STAR_COUNT = 140;
  const stars = Array.from({ length: STAR_COUNT }, () => ({
    x:     Math.random(),
    y:     Math.random(),
    r:     Math.random() * 1.2 + 0.3,
    alpha: Math.random() * 0.6 + 0.1,
    speed: Math.random() * 0.004 + 0.001,
    phase: Math.random() * Math.PI * 2
  }));

  let frame = 0;
  function draw() {
    frame++;
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    stars.forEach(s => {
      const a = s.alpha * (0.5 + 0.5 * Math.sin(s.phase + frame * s.speed));
      ctx.beginPath();
      ctx.arc(s.x * canvas.width, s.y * canvas.height, s.r, 0, Math.PI * 2);
      ctx.fillStyle = `rgba(180,170,255,${a})`;
      ctx.fill();
    });
    requestAnimationFrame(draw);
  }
  draw();
}

