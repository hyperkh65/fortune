/* ──────────────────────────────────────────────────────
   SEARCH
────────────────────────────────────────────────────── */
function searchDreams(query, category) {
  const q = (query || '').trim().toLowerCase();

  return DREAM_DB.filter(item => {
    // Category filter
    if (category !== 'all' && item.category !== category) return false;

    // Text search
    if (!q) return true;

    return (
      item.name.toLowerCase().includes(q)     ||
      item.short.toLowerCase().includes(q)    ||
      item.meaning.toLowerCase().includes(q)  ||
      (item.tags && item.tags.some(t => t.toLowerCase().includes(q)))
    );
  });
}

/* ──────────────────────────────────────────────────────
   RENDER CARDS
────────────────────────────────────────────────────── */
function renderCards(items) {
  const grid      = document.getElementById('resultsGrid');
  const metaCount = document.getElementById('resultsCount');
  const empty     = document.getElementById('emptyState');

  if (!grid) return;

  if (items.length === 0) {
    grid.innerHTML   = '';
    grid.style.display = 'none';
    empty.classList.add('show');
    metaCount.innerHTML = '';
    return;
  }

  grid.style.display = '';
  empty.classList.remove('show');

  const catLabel = currentCategory === 'all'
    ? '전체'
    : CATEGORY_INFO[currentCategory]?.label || currentCategory;

  metaCount.innerHTML = currentQuery
    ? `<strong>${items.length}개</strong>의 꿈 상징이 "<strong>${escHtml(currentQuery)}</strong>"에 해당합니다`
    : `<strong>${catLabel}</strong> 카테고리 · <strong>${items.length}개</strong>의 꿈 상징`;

  grid.innerHTML = items.map(item => buildCardHTML(item)).join('');

  // Re-attach toggle listeners
  grid.querySelectorAll('.dc-expand-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const id   = btn.dataset.id;
      const card = btn.closest('.dream-card');
      if (!card) return;
      const isOpen = expandedCards.has(id);
      if (isOpen) {
        expandedCards.delete(id);
        card.classList.remove('expanded');
        btn.querySelector('.dc-expand-arrow').textContent = '▼';
      } else {
        expandedCards.add(id);
        card.classList.add('expanded');
        btn.querySelector('.dc-expand-arrow').textContent = '▲';
      }
    });
  });
}

/* ──────────────────────────────────────────────────────
   CARD HTML BUILDER
────────────────────────────────────────────────────── */
function buildCardHTML(item) {
  const omen    = OMEN_INFO[item.omen] || OMEN_INFO.neutral;
  const catInfo = CATEGORY_INFO[item.category] || {};
  const isOpen  = expandedCards.has(item.id);

  const tagsHTML = (item.tags || [])
    .slice(0, 6)
    .map(t => `<span class="dc-tag">${escHtml(t)}</span>`)
    .join('');

  const luckyHTML = item.lucky ? `
    <div class="dc-lucky-row">
      <div class="dc-lucky-item">
        <div class="dc-lucky-label">행운색</div>
        <div class="dc-lucky-val">${escHtml(item.lucky.color)}</div>
      </div>
      <div class="dc-lucky-item">
        <div class="dc-lucky-label">행운 숫자</div>
        <div class="dc-lucky-val">${item.lucky.number}</div>
      </div>
      <div class="dc-lucky-item">
        <div class="dc-lucky-label">행운 방향</div>
        <div class="dc-lucky-val">${escHtml(item.lucky.direction)}</div>
      </div>
    </div>
  ` : '';

  return `
    <div class="dream-card${isOpen ? ' expanded' : ''}" data-id="${escHtml(item.id)}">
      <div class="dc-top">
        <div class="dc-emoji">${item.emoji}</div>
        <div class="dc-info">
          <div class="dc-name">${escHtml(item.name)}</div>
          <div class="dc-short">${escHtml(item.short)}</div>
        </div>
      </div>
      <div class="dc-badges">
        <span class="dc-cat-badge">${catInfo.icon || ''} ${catInfo.label || item.category}</span>
        <span class="dc-omen-badge ${omen.cls}">${omen.label}</span>
      </div>
      <button class="dc-expand-btn" data-id="${escHtml(item.id)}" aria-label="상세 해몽 보기">
        상세 해몽 <span class="dc-expand-arrow">${isOpen ? '▲' : '▼'}</span>
      </button>
      <div class="dc-body">
        <p class="dc-meaning">${escHtml(item.meaning)}</p>
        ${luckyHTML}
        ${tagsHTML ? `<div class="dc-tags">${tagsHTML}</div>` : ''}
      </div>
    </div>
  `;
}

