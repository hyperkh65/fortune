/* ──────────────────────────────────────────────────────
   DAILY DREAM (date-seeded)
────────────────────────────────────────────────────── */
function getDailyDream() {
  const today = new Date();
  const seed  = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  const index = seed % DREAM_DB.length;
  return DREAM_DB[index];
}

